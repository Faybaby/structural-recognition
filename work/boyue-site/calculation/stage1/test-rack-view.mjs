import assert from 'node:assert/strict';
import {formedRackView} from '../../stage1/rack-view.js';
const positions=['a','b','c','d','x'].map(uid=>({uid,layer:'L3'}));
const poles=positions;
const rods=[['a','b'],['b','c'],['c','d'],['d','a'],['a','x']].map(([a,b],i)=>({id:i,a,b,level:200}));
const result={positions,poles,rods,cells:[{id:'C1',level:200,vertices:['a','b','c','d']}]};
const original=JSON.stringify(result),view=formedRackView(result);
assert.equal(view.cells.length,1);assert.equal(view.poles.length,4);assert.equal(view.rods.length,4);assert(!view.uids.has('x'));
assert.equal(formedRackView(result,'L4').cells.length,0);
assert.equal(formedRackView({...result,cells:[]}).poles.length,0);
assert.equal(formedRackView({...result,rods:[...rods,{a:'a',b:'b',level:1700}]}).rods.length,4);
assert.equal(JSON.stringify(result),original);
console.log('PASS: closed perimeter only, shared-pole branch excluded, level/scope/empty state, immutable results');
import * as THREE from '../../model3d/vendor/three.module.js';
import {createRackThree} from '../../stage1/rack-three.js';
const fullPositions=positions.map((p,i)=>({...p,world:[[0,0],[900,0],[900,900],[0,900],[1800,0]][i],kind:'floor',top:4000,bottom:0,levels:[200],status:'found'}));
const model={...result,positions:fullPositions,poles:fullPositions,config:{diameter:48,primary:900},highSupports:[],changes:[],cancelled:[]};
const rendered=createRackThree({THREE,result:model,view:{isolate:true,aligned:true,model:true},scope:'all',centerX:0,centerZ:0,visibleKinds:{floor:false}});
assert.equal(rendered.meshes.length,5);
assert(rendered.meshes.every(m=>m.count===4));
console.log('PASS: real THREE meshes isolate four poles/four rods and retain cell dots even when floor results hidden');
